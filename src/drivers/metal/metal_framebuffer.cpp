#include "drivers/metal/metal_framebuffer.h"
#include "Metal/MTLPixelFormat.hpp"
#include "Metal/MTLRenderPass.hpp"
#include "Metal/MTLTexture.hpp"
#include "drivers/metal/metal_texture_2d.h"

namespace Primitive {
    MetalFramebuffer::MetalFramebuffer(MTL::Device* device, const FramebufferDesc& desc) : device_(device), desc_(desc) {
        invalidate();
    }

    MetalFramebuffer::~MetalFramebuffer() {
        if (msaa_color_texture_) msaa_color_texture_->release();
        if (depth_texture_) depth_texture_->release();
        if (render_pass_descriptor_) render_pass_descriptor_->release();
    }

    void MetalFramebuffer::resize(uint32_t width, uint32_t height) {
        if (desc_.width == width && desc_.height == height) return;
        desc_.width = width;
        desc_.height = height;
        invalidate();
    }

    void MetalFramebuffer::invalidate() {
        if (msaa_color_texture_) msaa_color_texture_->release();
        if (depth_texture_) depth_texture_->release();
        if (render_pass_descriptor_) render_pass_descriptor_->release();

        // Generated by Gemini 3.6 Flash
        auto* msaa_desc = MTL::TextureDescriptor::alloc()->init();
        msaa_desc->setTextureType(desc_.sample_count > 1 ? MTL::TextureType2DMultisample : MTL::TextureType2D);
        msaa_desc->setPixelFormat(static_cast<MTL::PixelFormat>(desc_.color_attachment.format));
        msaa_desc->setWidth(desc_.width);
        msaa_desc->setHeight(desc_.height);
        msaa_desc->setSampleCount(desc_.sample_count);
        msaa_desc->setUsage(MTL::TextureUsageRenderTarget);
        msaa_color_texture_ = device_->newTexture(msaa_desc);
        msaa_desc->release();

        auto* resolve_desc = MTL::TextureDescriptor::alloc()->init();
        resolve_desc->setTextureType(MTL::TextureType2D);
        resolve_desc->setPixelFormat(static_cast<MTL::PixelFormat>(desc_.color_attachment.format));
        resolve_desc->setWidth(desc_.width);
        resolve_desc->setHeight(desc_.height);
        resolve_desc->setUsage(MTL::TextureUsageRenderTarget | MTL::TextureUsageShaderRead);
        resolve_desc->setStorageMode(MTL::StorageModePrivate);

        NS::SharedPtr<MTL::Texture> resolve_tex = NS::TransferPtr(device_->newTexture(resolve_desc));
        resolved_color_texture_ = std::make_shared<MetalTexture2D>(resolve_tex);
        resolve_desc->release();


        auto* depth_desc = MTL::TextureDescriptor::alloc()->init();
        depth_desc->setTextureType(desc_.sample_count > 1 ? MTL::TextureType2DMultisample : MTL::TextureType2D);
        depth_desc->setPixelFormat(static_cast<MTL::PixelFormat>(desc_.depth_attachment.format));
        depth_desc->setWidth(desc_.width);
        depth_desc->setHeight(desc_.height);
        depth_desc->setUsage(MTL::TextureUsageRenderTarget);
        depth_desc->setSampleCount(desc_.sample_count);
        depth_texture_ = device_->newTexture(depth_desc);
        depth_desc->release();

        // End gen

       render_pass_descriptor_ = MTL::RenderPassDescriptor::alloc()->init();

       auto* color_attach = render_pass_descriptor_->colorAttachments()->object(0);
       color_attach->setTexture(msaa_color_texture_);
       color_attach->setResolveTexture(static_cast<MTL::Texture*>(resolved_color_texture_->get_native_handle()));
       color_attach->setLoadAction(desc_.color_attachment.clear_on_load ? MTL::LoadActionClear : MTL::LoadActionLoad);
       color_attach->setClearColor(MTL::ClearColor(
           desc_.color_attachment.clear_color.r,
           desc_.color_attachment.clear_color.g,
           desc_.color_attachment.clear_color.b,
           desc_.color_attachment.clear_color.a
       ));

       color_attach->setStoreAction(desc_.sample_count > 1 ? MTL::StoreActionMultisampleResolve : MTL::StoreActionStore);

       auto* depth_attach = render_pass_descriptor_->depthAttachment();
       depth_attach->setTexture(depth_texture_);
       depth_attach->setLoadAction(desc_.depth_attachment.clear_on_load ? MTL::LoadActionClear : MTL::LoadActionLoad);
       depth_attach->setStoreAction(MTL::StoreActionDontCare);
       depth_attach->setClearDepth(desc_.depth_attachment.clear_depth);




    }


}
